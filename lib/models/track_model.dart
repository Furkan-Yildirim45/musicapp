class TrackModel {
  final String title;
  final String artist;
  final String views;
  final String image;
  final String lyrics;
  final String duration;
  final String audioUrl;

  TrackModel({
    required this.title,
    required this.artist,
    required this.views,
    required this.image,
    required this.lyrics,
    required this.duration,
    required this.audioUrl,
  });
} 